#!/usr/bin/env node
/* Generates frontend/env.js from frontend/.env (optional helper; plain Node, no dependencies).
   Usage:  cd frontend && cp .env.example .env && node scripts/generate-env.js */
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const src = fs.existsSync(path.join(root, ".env")) ? path.join(root, ".env") : path.join(root, ".env.example");
const kv = {};
fs.readFileSync(src, "utf8").split(/\r?\n/).forEach((l) => { const m = l.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/); if (m && !l.trim().startsWith("#")) kv[m[1]] = m[2]; });
const num = (k, d) => (Number.isFinite(Number(kv[k])) && kv[k] !== undefined && kv[k] !== "" ? Number(kv[k]) : d);
const bool = (k) => String(kv[k] || "").toLowerCase() === "true";
const mode = ["demo", "live"].includes(kv.DEFAULT_MODE) ? kv.DEFAULT_MODE : "demo";
const env = { API_BASE_URL: kv.API_BASE_URL || "", API_PREFIX: kv.API_PREFIX || "/api", REQUEST_TIMEOUT_MS: num("REQUEST_TIMEOUT_MS", 10000), DEFAULT_MODE: mode,
  USE_MOCK_API: bool("USE_MOCK_API"), MOCK_LATENCY_MS: num("MOCK_LATENCY_MS", 250), WEATHER_LOCATION_LABEL: kv.WEATHER_LOCATION_LABEL || "Abbottabad", DEBUG: bool("DEBUG") };
const out = "/* GENERATED by scripts/generate-env.js from " + path.basename(src) + " — public values only, never put secrets here. */\nwindow.WW_ENV = " + JSON.stringify(env, null, 2) + ";\n";
fs.writeFileSync(path.join(root, "env.js"), out);
console.log("env.js written from " + path.basename(src), env);
